def analyze_message(text):
    """
    Анализирует сообщение пользователя.
    Возвращает уровень состояния и ответ.
    """

    text = text.lower()

    critical_words = [
        "хочу умереть",
        "не хочу жить",
        "покончу с собой",
        "убить себя",
        "не проснуться",
        "умереть"
    ]

    warning_words = [
        "очень плохо",
        "одиноко",
        "никому не нужен",
        "устал",
        "тяжело",
        "плохо"
    ]


    for word in critical_words:
        if word in text:
            return {
                "level": "critical",
                "score": 3,
                "response": (
                    "Мне важно, чтобы ты сейчас был в безопасности.\n\n"
                    "Ответь, пожалуйста:\n"
                    "1. Ты сейчас один?\n"
                    "2. Есть ли рядом что-то, чем можно навредить себе?\n"
                    "3. Ты можешь убрать это подальше?"
                )
            }


    for word in warning_words:
        if word in text:
            return {
                "level": "warning",
                "score": 2,
                "response": (
                    "Я слышу тебя. Похоже, сейчас непростой момент.\n\n"
                    "Давай разберёмся спокойно.\n"
                    "Что именно сейчас самое тяжёлое?"
                )
            }


    return {
        "level": "normal",
        "score": 0,
        "response": (
            "Я рядом 🤖\n"
            "Расскажи подробнее, что происходит."
        )
    }